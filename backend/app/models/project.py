"""PROJECTS: a project with its own tasks, statuses, spaces and task numbering.

Schema: docs/database.md, section 3.3.
Timestamps: created_at, updated_at come from TimestampMixin (app/db/base.py).
"""

from datetime import date
from enum import StrEnum

from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    ForeignKey,
    Integer,
    String,
    Text,
    UniqueConstraint,
)
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base, BigIntPK, TimestampMixin

PROJECT_NAME_MAX_LENGTH = 150
PROJECT_PUBLIC_ID_MAX_LENGTH = 16
PROJECT_STATUS_MAX_LENGTH = 20
TASK_PREFIX_MAX_LENGTH = 10
# 2–10 characters: an uppercase letter, then uppercase letters or digits ("WEB", "APP2").
TASK_PREFIX_PATTERN = r"^[A-Z][A-Z0-9]{1,9}$"


class ProjectStatus(StrEnum):
    """Allowed values of projects.status (P-5). Shared with the API schemas."""

    ACTIVE = "active"
    ON_HOLD = "on_hold"
    COMPLETED = "completed"
    ARCHIVED = "archived"  # read-only; set only by the archive endpoint (PRJ-5)


_STATUS_VALUES = ", ".join(f"'{status.value}'" for status in ProjectStatus)


class Project(TimestampMixin, Base):
    __tablename__ = "projects"
    __table_args__ = (
        UniqueConstraint("public_id"),  # uq_projects_public_id (PDF #9)
        # uq_projects_organization_id_task_prefix (PDF #9). organization_id is its
        # leftmost column, so it also serves "projects of this organization"; no
        # separate organization_id index is created (P-7).
        UniqueConstraint("organization_id", "task_prefix"),
        CheckConstraint(f"status IN ({_STATUS_VALUES})", name="status"),
        CheckConstraint(
            f"task_prefix ~ '{TASK_PREFIX_PATTERN}'", name="task_prefix_format"
        ),
        CheckConstraint("next_task_number >= 1", name="next_task_number_positive"),
        CheckConstraint(
            "start_date IS NULL OR end_date IS NULL OR end_date >= start_date",
            name="date_range",
        ),
    )

    id: Mapped[BigIntPK]  # internal only; URLs and the API use public_id
    organization_id: Mapped[int] = mapped_column(
        BigInteger,  # explicit: don't rely on borrowing the type from organizations.id
        ForeignKey("organizations.id", ondelete="NO ACTION"),
    )
    # Random URL-safe id, generated by the project service (app/utils/ids.py).
    public_id: Mapped[str] = mapped_column(String(PROJECT_PUBLIC_ID_MAX_LENGTH))
    name: Mapped[str] = mapped_column(String(PROJECT_NAME_MAX_LENGTH))
    status: Mapped[str] = mapped_column(
        String(PROJECT_STATUS_MAX_LENGTH),
        server_default=ProjectStatus.ACTIVE.value,
    )
    description: Mapped[str | None] = mapped_column(Text)
    task_prefix: Mapped[str] = mapped_column(String(TASK_PREFIX_MAX_LENGTH))
    # The next number to hand out (PDF #3, replaces the TASK_COUNT table). Only ever
    # changed by one atomic statement inside task creation:
    #   UPDATE projects SET next_task_number = next_task_number + 1 ... RETURNING ...
    # (docs/database.md, section 3.3). Never returned by the API.
    next_task_number: Mapped[int] = mapped_column(Integer, server_default="1")
    start_date: Mapped[date | None]
    end_date: Mapped[date | None]

    # No relationship collections (project.tasks, .spaces, .teams, ...): those are
    # fetched by repositories with filters and pagination (relationship policy, B7).
